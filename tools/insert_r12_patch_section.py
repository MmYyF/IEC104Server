import io

path = "docs/代码分析报告.md"
marker = "### 10.18 本层尚未覆盖的部分"

section = """#### 八、补丁（1.7.1）：最大化时标题栏被屏幕顶边切掉

第十二轮交付后用户又提了一句：

> "这一栏放大后还是感觉图标和按钮都比较靠上，可以适当将这一栏加宽一点，
> 然后将图标和按钮上下居中对齐。"

先说结论：**内容本来就是居中的，问题不在对齐，而在"参照系"。**

上一轮加的 `titlebar-center` 断言量的是"控件中心对**标题栏**中线的偏差"，
它一直是 +0.4px 全绿——而且它是对的。但用户看到的仍然偏上，
因为出问题的是**标题栏本身**：最大化时窗口比屏幕工作区大一圈，
多出来的那一圈落在顶部，标题栏最上面 9 物理像素压根不在屏幕上。

##### 一、把"感觉"量成数字

用户给的截图是 2554×41。这个 41 是破案的关键：

- 标题栏 40 逻辑像素 × 1.25 缩放 = **50 物理像素**；
- 可见的只有 **41**，差 9；
- 用 Pillow 逐行统计墨迹：`logo/菜单` 的墨迹在 y=5..27，中心 16；
  按完整 50 高居中应该落在 25。16 对 41 = **39%**，而居中应该是 50%。

41 = 50 − 9，且 9 这个数字和窗口外扩量正好对上。于是去量窗口：

```
还原态  client=1530x876  origin=(515,252)
最大化  window=(-9,-9,2569,1389)  client=2578x1398  origin=(-9,-9)
工作区  2560x1380
```

客户区原点在屏幕 `(-9,-9)`——**顶部 9 像素、左侧 9 像素被切掉，
底部和右侧 9 像素落到屏幕外/任务栏后面**。这就是全部原因。

##### 二、两条弯路（都值得记下来）

**弯路一：按"对称溢出"算边距。** 第一版用
`(客户区尺寸 − 工作区尺寸) / 2` 算补偿量，在测试时**又错了**：
实测窗口有时落在 `(-9,-9)`、有时落在 `(0,0)`，两种都真实出现过。
落在 `(0,0)` 时顶部根本没被裁（多出来的 18 全在右侧和底部），
而对称公式照样给顶部加了 9px，结果顶部凭空多出一条空白带、内容整体偏下。

改成**按边算**：用 `窗口位置 vs 工作区` 一条边一条边算，哪条被裁补哪条。

**弯路二：只算一次。** 边距依赖窗口位置，而最大化之后系统会把窗口位置
摆两次（先按"工作区 − 不可见边框"摆，随后再修正一次）。
只在 `WindowState` 变化时算一次，就会拿着旧位置算出的边距一直贴着不放——
表现又回到"顶部一条 9px 空白带"。

最终的信号组合：

| 信号 | 干什么 |
|---|---|
| `WindowState` 变化 | 立刻算一次，并起一个 60 ms 的短定时器补算约 0.4 秒 |
| `ClientSize` 变化 | 立刻算一次 |
| `PositionChanged` | 立刻算一次（**这条最关键**，位置变了旧边距就错） |

##### 三、断言为什么没能拦住它

这是这一轮最值得写的教训：**量对了数值，量错了参照系，一样会得出"没问题"的结论。**

`titlebar-center` 的参照系是"标题栏"，而标题栏有一半在屏幕外——
在这个参照系里，永远量不出问题。新断言把参照系换成**屏幕坐标**：

```
titlebar-maximized: 窗口@(-9,-9) 工作区=2560x1380 边距=(7.2,7.2,7.2,7.2)
                    栏顶屏幕y=0(应 0) 状态栏底屏幕y=1380(应 1380)
                    栏高=46.4 内容偏移=0.4 => PASS
```

不变式只有两条，但和窗口摆在哪无关：

- **标题栏顶边在屏幕上的 y 必须等于工作区顶边**；
- **状态栏底边在屏幕上的 y 必须等于工作区底边**。

顺手补掉了同一个毛病在底部的表现：原来状态栏最下面 9 像素也是被任务栏盖住的，
只是没人提。

##### 四、标题栏高度 40 → 46

除了裁剪，40 本身也偏挤：同一行塞了 18px 图标、16px 菜单图标、28px 系统按钮，
上下各只余 6px，看着就是"贴着头"。加到 **46** 后上下各余 9px。

##### 五、验收

- `--capture-ui` **55 PASS / 0 FAIL**（54 + 新增 `titlebar-maximized`）；
- 屏幕实测 A/B（同一台机器、同一缩放）：

  | | 标题栏可见高度 | 墨迹中心 | 占可见高度 |
  |---|---:|---:|---:|
  | 修复前（用户截图） | 41 物理px | y=16 | **39%**（偏上） |
  | 修复后 | 56 物理px | y=29 | **51%**（居中） |

- 状态栏底边实测 `1379`，任务栏从 `1380` 开始——正好贴住，不再被盖；
- 发布单文件 exe **脱运行时**再跑一遍 capture：55/55；
- 版本号 1.7.0 → **1.7.1**。

"""

text = io.open(path, encoding="utf-8").read()
assert text.count(marker) == 1, text.count(marker)
text = text.replace(marker, section + marker)
io.open(path, "w", encoding="utf-8", newline="").write(text)
print("inserted, lines =", text.count("\n") + 1)
